def 소리구간(a, b, 여유=0.25):
    """[a,b] 에서 **실제로 소리가 나는** 처음·끝을 잰다 (초).

    ★ASR 낱말 시각은 뒤 침묵을 물고 있다. 「발뺌하지 말고요」는 ASR 이 31.92 까지라
      적었지만 소리는 **31.82 에 이미 끝났고**, 그 사이 31.865 에 장면전환이 있었다.
      ASR 만 믿으면 «말을 자른다» 며 못 끊고 0.80초 조각을 남긴다.
      소리를 재면 «여기서 끊어도 된다» 를 알 수 있다.
    """
    import numpy as _np
    r = subprocess.run(['ffmpeg', '-v', 'error', '-ss', '%.3f' % max(0, a - 여유),
                        '-to', '%.3f' % (b + 여유), '-i', SRC, '-vn', '-ac', '1',
                        '-ar', '16000', '-f', 'f32le', '-'], capture_output=True)
    x = _np.frombuffer(r.stdout, dtype='<f4')
    if x.size < 320:
        return None, None
    n = 320                                   # 20ms
    칸 = _np.sqrt((x[:len(x) // n * n].reshape(-1, n) ** 2).mean(axis=1) + 1e-12)
    바닥 = float(_np.percentile(칸, 20))       # 룸톤
    문턱 = max(바닥 * 2.5, float(칸.max()) * 0.10)
    울림 = _np.where(칸 > 문턱)[0]
    if not len(울림):
        return None, None
    t0 = max(0, a - 여유)
    return t0 + float(울림[0]) * 0.02, t0 + float(울림[-1] + 1) * 0.02

