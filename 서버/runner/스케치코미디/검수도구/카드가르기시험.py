"""카드가르기시험.py — 뭉친 픽셀 카드를 읽힌 글줄이 바뀌는 자리에서 가르는가 (s2pipe/번인관문.글줄가르기 · 확인된카드들).

왜 (2026-10-04 루키치67 · 수리C)
  픽셀 카드 검출이 132.6~143.9 를 카드 하나로 뭉쳤다(안에 글줄 다섯 문장). 경계제안·카드경계검사(둘 다 확인된카드들 — 같은 목록)는
  «경계가 카드 한가운데» 를 문장 자르기로 보는데, 뭉친 카드에선 문장 사이도 한가운데라 가짜 제안이 나왔다.
  표본은 납품 캐시(work/루키치67.mp4.카드상자.json · 루키치160)에서 옮긴 실제 값.

쓰는 법
  ~/.volcano/venv/bin/python3 카드가르기시험.py      종료코드 0 = 맞음
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from s2pipe import 번인관문 as 관   # noqa: E402

틀림 = []


def 봄(이름, 참, 덧=""):
    print(("[OK] " if 참 else "[X] ") + 이름 + (f" — {덧}" if 덧 else ""))
    if not 참:
        틀림.append(이름)


# 루키치67 132.6~143.9 — 0.5초 표본 글줄(실제 프레임 시각)
글67 = [(136.208, "왜 그랬니?")] + [(t, "죄송해요 몰랐습니다") for t in (136.708, 137.208, 137.708, 138.208)] \
    + [(t, "아빠 오늘 늦게 들어간다.") for t in (138.708, 139.208, 139.708, 140.208)] \
    + [(t, "엄마 자면 연락하도록") for t in (140.708, 141.208, 141.708)] + [(t, "예 아버지..") for t in (142.208, 142.708, 143.208, 143.708)]
r = 관.글줄가르기([(132.6, 143.9)], 글67)
봄("루키치67 뭉친 카드 → 네 문장 경계에서 가름", r == [(132.6, 138.46), (138.46, 140.46), (140.46, 141.96), (141.96, 143.9)], str(r))

# 한 장에 두 줄(식단 목록) — 줄이 번갈아 와도 같은 장이면 한 글로 본다(루키치160 96.3~101.4 가 9조각으로 갈리던 꼴)
글160 = []
for i in range(10):
    t = 96.458 + 0.5 * i
    글160 += [(t, "저녁 고등어구이", 900), (t, "아침 닭가슴살고, 밥" + ("1" if i % 2 else "고"), 950)]
r = 관.글줄가르기([(96.3, 101.4)], 글160)
봄("두 줄 자막 번갈아 → 가르지 않음", r == [(96.3, 101.4)], str(r))

# 인식 쓰레기 한 장·같은 말 흔들림 — 가르지 않음
글쓰 = [(10.2, "힘 조절 잘못했네"), (10.7, "힘 조절 잘못했네"), (11.2, "10l0곱IC극ㄹ"), (11.7, "힘 조절 잘못햇네"), (12.2, "힘 조절 잘못했네")]
r = 관.글줄가르기([(10.0, 12.5)], 글쓰)
봄("쓰레기 한 장 끼어도 → 가르지 않음", r == [(10.0, 12.5)], str(r))
봄("글줄 없으면 그대로", 관.글줄가르기([(1.0, 2.0)], []) == [(1.0, 2.0)])
print(f"틀림 {len(틀림)}")
sys.exit(1 if 틀림 else 0)
