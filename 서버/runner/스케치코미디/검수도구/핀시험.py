from s2pipe import sync   # noqa: E402

틀림 = []


def 봄(이름, 참, 덧=""):
    print(("[OK] " if 참 else "[X] ") + 이름 + (f" — {덧}" if 덧 else ""))
    if not 참:
        틀림.append(이름)


def 건다(줄, 핀, words=()):
    dlg = copy.deepcopy(줄)
    proj = {"문구교정": 핀, "segments": [{"t0": 0, "t1": 20, "keep": True}]}
    sync.문구교정적용(dlg, proj, list(words), [])
    return sorted(dlg, key=lambda d: d["t"])


기본 = [{"t": 1.7, "t1": 2.69, "text": "나 말고 다른 남자랑"},
        {"t": 6.08, "t1": 8.3, "text": "카톡 로그아웃이 안 됐네"},
        {"t": 8.9, "t1": 9.35, "text": "헐 미친"}]

