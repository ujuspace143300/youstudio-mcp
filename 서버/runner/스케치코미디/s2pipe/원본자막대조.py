import difflib
import os
import re

글자 = re.compile(r"[가-힣0-9A-Za-z]")

창앞, 창뒤 = 1.0, 1.0          # 줄 원본 시각 창 — 박힌 자막은 말보다 먼저 뜨고 늦게 진다(2fps 표본)
카드여유 = 0.3
최소카드 = 10                  # 박힌 자막 있는 원본 — 루키치 161편 최소 33장
최소자리비율 = 0.5             # 대사 줄 중 원본 자막과 같은 자리인 비율 — 루키치 최소 0.69(14 · 가사 13줄 포함)
괄호닮음 = 0.5
노래줄, 노래초, 노래틈 = 5, 7.0, 3.0
노래전사창, 노래전사비율 = 2.0, 0.2      # 연속 줄마다 원본 시각 ±2초 안의 원본 전사 줄 수 ≤ 연속 줄 수 × 0.2 — 14: 0/13 · 274: 9/10 · 229: 4/7
# 휴대폰·배달 앱 알림 목소리 — 관찰: 카톡(루키치11·67·195·168) · 배달의민족 주문(4). 요기요·쿠팡이츠는 같은 꼴(앱 알림 음성)이라 같이 둔다.
알림말 = re.compile(r"(?:카톡|배달의민족주문|배민주문|요기요|쿠팡이츠주문)+")


def 원본그림(proj):
    """완성본 시각 → 원본 시각 표 [(완성본 시작, 원본 t0, 원본 t1)] — keep 조각 재생 순서."""
    g, 누 = [], 0.0
    for s in proj.get("segments", []):
        if not s.get("keep", True):
            continue
        g.append((누, s["t0"], s["t1"]))
        누 += s["t1"] - s["t0"]
    return g


def _원(그림, tc):
    for c0, o0, o1 in 그림:
        if c0 - 1e-6 <= tc < c0 + (o1 - o0):
            return o0 + (tc - c0), o1
    return None, None


def _닮음(a, b):
    a = "".join(글자.findall(a))
    b = "".join(글자.findall(b))
    if not a:
        return None
    if not b:
        return 0.0
    return sum(x.size for x in difflib.SequenceMatcher(None, a, b, autojunk=False).get_matching_blocks()) / len(a)


def 자료(src):
    """(확인된 카드 [(t0,t1)], 박힌 대사 자막 글줄 [(t, 글)]) — 원본 옆 캐시(굽기 관문이 이미 만든 것)를 쓴다."""
    from . import 번인관문
    from . import 화면글자 as 글
    cards = 번인관문.확인된카드들(src)
    c = 글._캐시(src)
    표본 = [(t, l["s"]) for t, l in 글.자막표본(c["frames"], 글._띠(src))]
    return cards, 표본


def 원본전사읽기(vtt):
    """원본 전사 vtt → [(원본 시각, 글)] — 없거나 못 읽으면 None."""
    if not vtt or not os.path.exists(vtt):
        return None
    out = []
    for b in open(vtt, encoding="utf-8").read().split("\n\n"):
        ls = b.strip().splitlines()
        if len(ls) >= 2 and "-->" in ls[0]:
            try:
                h, m, s = ls[0].split(" --> ")[0].split(":")
                out.append((int(h) * 3600 + int(m) * 60 + float(s), " ".join(ls[1:])))
            except ValueError:
                continue
    return out


def 판정(dlg, 그림, cards, 표본, 원줄=None):
    """dlg(대사 줄 — t·t1·text·_핀·_더하기핀)를 보고 {"켜짐", "까닭", "빼기": [(줄, 까닭)], "주의": [줄]} — dlg 는 바꾸지 않는다.
    원줄 = 원본 전사 [(원본 시각, 글)] — 없으면(None) 노래 빼기를 하지 않는다(주의만)."""
    표본 = sorted(표본)
    줄들 = []
    for d in sorted(dlg, key=lambda x: x["t"]):
        to, o1 = _원(그림, d["t"])
        if to is None:
            continue
        t1 = d.get("t1") or d["t"] + 1.0
        te = min(to + max(0.0, t1 - d["t"]), o1)
        창 = " ".join(g for t, g in 표본 if to - 창앞 <= t <= te + 창뒤)
        카드 = any(cs < te + 카드여유 and ce > to - 카드여유 for cs, ce in cards)
        줄들.append({"d": d, "원": round(to, 2), "원끝": round(te, 2), "창": 창, "카드": 카드, "빈창": not 창.strip() and not 카드,
                    "핀": bool(d.get("_핀") or d.get("_더하기핀")), "괄호": d.get("text", "").lstrip().startswith("(")})
    대사 = [x for x in 줄들 if not x["괄호"]]
    자리 = sum(1 for x in 대사 if not x["빈창"]) / len(대사) if 대사 else 0.0
    out = {"켜짐": False, "빼기": [], "주의": [], "자리비율": round(자리, 2), "카드수": len(cards)}
    if len(cards) < 최소카드 or 자리 < 최소자리비율:
        out["까닭"] = f"원본 박힌 자막 없음(확인된 카드 {len(cards)}장 · 원본 자막 자리 {자리:.0%})"
        return out
    out["켜짐"] = True
    뺌 = set()
    # ① 괄호 설명 줄
    for x in 줄들:
        if x["괄호"] and not x["핀"]:
            속 = x["d"]["text"].strip().strip("()（）")
            닮 = _닮음(속, x["창"])
            if 닮 is None or 닮 < 괄호닮음:
                out["빼기"].append((x["d"], f"괄호 설명 줄 — 원본 자막에 없는 글(닮음 {0 if 닮 is None else 닮:.2f})"))
                뺌.add(id(x["d"]))
    # ② 노래(긴 무자막 소리) — 핀 없는 대사 줄의 «빈창» 연속
    i = 0
    while i < len(대사):
        if not (대사[i]["빈창"] and not 대사[i]["핀"]):
            i += 1
            continue
        j = i
        while (j + 1 < len(대사) and 대사[j + 1]["빈창"] and not 대사[j + 1]["핀"]
               and 대사[j + 1]["d"]["t"] - (대사[j]["d"].get("t1") or 대사[j]["d"]["t"] + 1.0) < 노래틈):
            j += 1
        덩 = 대사[i:j + 1]
        길이 = (덩[-1]["d"].get("t1") or 덩[-1]["d"]["t"] + 1.0) - 덩[0]["d"]["t"]
        전사 = None if 원줄 is None else sum(1 for t, _g in 원줄
                                              if any(x["원"] - 노래전사창 <= t <= x["원끝"] + 노래전사창 for x in 덩))
        if len(덩) >= 노래줄 and 길이 >= 노래초 and 전사 is not None and 전사 <= 노래전사비율 * len(덩):
            for x in 덩:
                out["빼기"].append((x["d"], f"노래 의심 — 원본 자막·카드 없는 줄 {len(덩)}개가 {길이:.1f}초 잇달음"
                                           f"· 원본 전사 {전사}줄(원본 {덩[0]['원']:.1f}~)"))
                뺌.add(id(x["d"]))
        i = j + 1
    # ③ 휴대폰 알림 소리
    for x in 대사:
        if x["핀"] or id(x["d"]) in 뺌:
            continue
        깨 = "".join(글자.findall(x["d"]["text"]))
        if 깨 and 알림말.fullmatch(깨):
            창깨 = "".join(글자.findall(x["창"]))
            말 = re.findall(r"카톡|배달의민족주문|배민주문|요기요|쿠팡이츠주문", 깨)
            if not any(m in 창깨 for m in 말):
                out["빼기"].append((x["d"], "휴대폰 알림 소리 — 원본 자막에 없는 알림 말"))
                뺌.add(id(x["d"]))
    out["주의"] = [x for x in 대사 if x["빈창"] and not x["핀"] and id(x["d"]) not in 뺌]
    return out


def 적용(dlg, proj, src, 면제구간, vtt=None, log=print):
    """sync 가 부른다 — 판정대로 dlg 에서 빼고(제자리) 면제구간에 더한다. 원본·캐시가 없으면 건너뛰고 알린다."""
    if not src or not os.path.exists(src):
        log(f"  주의  원본 자막 대조 건너뜀 — 원본 영상 없음({src})")
        return None
    try:
        cards, 표본 = 자료(src)
    except Exception as e:                                   # noqa: BLE001
        log(f"  주의  원본 자막 대조 건너뜀 — 카드·글자 인식 자료를 못 읽음: {str(e)[:100]}")
        return None
    원줄 = 원본전사읽기(vtt)
    if 원줄 is None:
        log(f"  주의  원본 전사 없음({vtt}) — 노래 의심 연속은 빼지 않고 주의로만")
    r = 판정(dlg, 원본그림(proj), cards, 표본, 원줄)
    if not r["켜짐"]:
        log(f"  [OK] 원본 자막 대조 — 끔: {r['까닭']}")
        return r
    for d, 까닭 in r["빼기"]:
        if d in dlg:
            dlg.remove(d)
        if not d.get("text", "").lstrip().startswith("("):
            면제구간.append((d["t"] - 0.3, (d.get("t1") or d["t"] + 2.0) + 0.3))
        log(f"  ★원본 자막 대조 — 뺌 [{d['t']:.1f}s] 「{d['text']}」 {까닭}")
    for x in r["주의"]:
        log(f"  주의  원본 박힌 자막에 없는 줄 [{x['d']['t']:.1f}s · 원본 {x['원']:.1f}s] 「{x['d']['text']}」 — 노래·알림·배경 말이면 "
            f"빼기 핀(\"\"), 대사가 맞으면 «=» 핀으로 둔다(자막대조표로 들어 보고)")
    log(f"  [OK] 원본 자막 대조 — 뺌 {len(r['빼기'])} · 주의 {len(r['주의'])} (카드 {r['카드수']}장 · 원본 자막 자리 {r['자리비율']:.0%})")
    return r
