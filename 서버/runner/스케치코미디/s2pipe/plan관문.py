# ── 전사·글 비교 ───────────────────────────────────────────────
def 큐읽기(vtt):
    """원본 전사 vtt → [(시작, 끝, 글)]. 없으면 []."""
    if not vtt or not os.path.exists(vtt):
        return []
    out = []
    for a, b, c, d, e, f, x in re.findall(r"(\d+):(\d+):([\d.]+) --> (\d+):(\d+):([\d.]+)[^\n]*\n(.+)",
                                         open(vtt, encoding="utf-8").read()):
        out.append((int(a) * 3600 + int(b) * 60 + float(c), int(d) * 3600 + int(e) * 60 + float(f),
                    re.sub(r"<[^>]+>", "", x).strip()))
    return out


def 뗀(s):
    return re.sub(r"[^0-9A-Za-z가-힣]", "", s or "")


def 닮음(글, 창글):
    """글(공백·부호 뗀) 의 두 글자 조각 가운데 창글 안에 있는 비율 (0~1)."""
    글, 창글 = 뗀(글), 뗀(창글)
    if len(글) < 2:
        return 1.0 if 글 and 글 in 창글 else 0.0
    조각 = [글[i:i + 2] for i in range(len(글) - 1)]
    return sum(1 for g in 조각 if g in 창글) / len(조각)


def _말큐(큐):
    """말 줄만 — 한글 2자 이상(추임새·효과 표기 거름)."""
    return [c for c in 큐 if len(re.sub(r"[^가-힣]", "", c[2])) >= 2]


# ── 파악 답(agy — 원본 통째로 보고 들은 답) 읽기 ───────────────
_시각 = re.compile(r"(\d{1,2}):(\d{2})(?:\s*[~\-–]\s*(\d{1,2}):(\d{2}))?")
_따옴 = re.compile(r"[\"“”]([^\"“”\n]{2,160})[\"“”]|«([^»\n]{2,160})»")


def 파악읽기(path):
    """파악 답(.md) → {"글": 원문, "로고": 초|None, "꼭남길": [{"글", "시각": [초…], "묶음": 번호}]}.
    형식은 agy 가 쓰는 대로라 들쭉날쭉하다 — «꼭 남길» 이 든 줄부터 «빼도·뺄» 이 든 줄 앞까지의 따옴표 대사만 뽑는다.
    시각은 그 줄(없으면 같은 번호 묶음의 앞 줄)에 적힌 [분:초]."""
    if not path or not os.path.exists(path):
        return None
    글 = open(path, encoding="utf-8").read()
    줄들 = 글.splitlines()
    로고 = None
    for 줄 in 줄들:
        if "로고" in 줄 and re.search(r"처음|나오|등장|끝 ?카드|시작", 줄) and not re.search(r"대사|쿠키", 줄):
            m = _시각.search(줄)
            if m:
                로고 = int(m[1]) * 60 + int(m[2])
                break
    꼭, 안, 묶음, 묶음시각 = [], False, 0, []
    for 줄 in 줄들:
        if not 안:
            # 절 제목이 편마다 다르다 — «꼭 남길»·«반드시 남길»·«필수 대사»·«남겨야 할» (점심이네 64편 실측)
            if re.search(r"남길 ?대사|남겨야|필수 ?대사|꼭 ?남길", 줄):
                안 = True
            continue
        if re.search(r"빼도|뺄 ?수|뺄 ?장면|빼면|생략|삭제|제외|잘라", 줄):
            break
        if re.match(r"\s*(\d+\.|#+|\*\*\d)", 줄):          # 새 번호 묶음
            묶음 += 1
            묶음시각 = []
        시 = [int(m[1]) * 60 + int(m[2]) for m in _시각.finditer(줄)]
        if 시:
            묶음시각 = 시
        for m in _따옴.finditer(줄):
            대사 = (m[1] or m[2] or "").strip()
            if len(뗀(대사)) >= 4:
                꼭.append({"글": 대사, "시각": 시 or list(묶음시각), "묶음": 묶음})
    return {"글": 글, "로고": 로고, "꼭남길": 꼭}


def 대사찾기(대사, 시각, 큐, 창=25.0, 기준=0.6):
    """따옴표 대사를 전사에서 찾는다 → (시작, 끝, 닮음) 또는 None. 적힌 시각 ±창 안의 줄 1~3개 이어 붙인 글과 견준다
    (파악 시각은 ±2초 어림이고 원본 전사도 1~2초 어긋난다 — 글로 찾고 시각은 좁히는 데만 쓴다)."""
    best = None
    for i in range(len(큐)):
        if 시각 and not any(abs(큐[i][0] - t) <= 창 for t in 시각):
            continue
        앞 = None
        for k in (1, 2, 3):
            if i + k > len(큐):
                break
            # 이어 붙이는 줄은 틈 1.5초 안만 — 멀리 떨어진 줄까지 붙이면 «찾은 자리» 가 15초로 부풀었다(점심이네6 실측)
            if k > 1 and 큐[i + k - 1][0] - 큐[i + k - 2][1] > 1.5:
                break
            s = 닮음(대사, "".join(c[2] for c in 큐[i:i + k]))
            # 줄을 더 붙여 0.05 넘게 오를 때만 넓힌다(같은 점수면 짧은 쪽)
            if 앞 is not None and s <= 앞 + 0.05:
                break
            앞 = s
            if best is None or s > best[2] + 1e-9:
                best = (큐[i][0], 큐[i + k - 1][1], s)
    if not best or best[2] < 기준:
        return None
    # agy 원본 전사의 줄 끝은 말끝보다 0.5~1초(길게는 3초) 늦다(make 주석 · 점심이네20 «난 자기랑 있을 때 제일 행복하지» 14자 줄이
    #   59.2~64.2초) — 덮임을 재는 끝은 글자 수로 어림한 말끝을 넘지 않게 한다(0.15초/자 + 0.6 — 스케치 말속도 8~10음절/초보다 넉넉히)
    return best[0], min(best[1], best[0] + 0.15 * len(뗀(대사)) + 0.6), best[2]


