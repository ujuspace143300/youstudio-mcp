@functools.lru_cache(maxsize=64)
def _크기(src):
    wh = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
                         "stream=width,height", "-of", "csv=p=0", src], capture_output=True, text=True).stdout
    try:
        W, H = (int(v) for v in wh.strip().split(",")[:2])
    except ValueError:
        return None
    return W, H


def 프레임(src, t):
    """원본의 t 초 한 장을 밝기(gray) 배열로. 못 뽑으면 None. (크기는 원본에서 잰다 — 1920x1080 을 박지 않는다:
    2026-10-03 Deep61 은 1920x960 이라 옛 준비 판정이 모든 컷을 «레터박스»로 냈다)"""
    wh = _크기(src)
    if not wh:
        return None
    W, H = wh
    r = subprocess.run(["ffmpeg", "-v", "error", "-ss", f"{t:.3f}", "-i", src, "-frames:v", "1",
                        "-f", "rawvideo", "-pix_fmt", "gray", "-"], capture_output=True)
    a = np.frombuffer(r.stdout, np.uint8)
    return a.reshape(H, W) if len(a) == W * H else None


def _변재기(b, 폭0, 폭1):
    """b = 가장자리에서 안쪽으로 본 배열(행 = 가장자리에서의 거리). 폭0:폭1 = 밝은 그림이 걸친 가로 범위.
    돌려줌 (두께, 순흑인가, 곧은경계인가, 잰 값)."""
    줄최대 = b.max(axis=1)
    k = 0
    while k < len(줄최대) and 줄최대[k] <= 어둠:
        k += 1
    if k < 최소두께 or k >= len(줄최대):
        return 0, False, False, {}
    띠 = b[:k].astype(np.int16)
    중앙 = float(np.median(띠))
    흔들림 = float(띠.std())
    안 = b[k:k + 3, 폭0:폭1].astype(np.int16)
    밝몫 = float((안 > 중앙 + 경계차).mean()) if 안.size else 0.0
    순흑 = 중앙 <= 순흑중앙 and 흔들림 <= 순흑흔들림
    return k, 순흑, 밝몫 >= 경계몫, {"두께": k, "중앙": round(중앙, 1), "흔들림": round(흔들림, 2), "경계몫": round(밝몫, 2)}


def _계단(b):
    """③ 완전 검정 띠의 줄 전체 계단. 맞으면 띠 두께, 아니면 0. (b 는 가장자리에서 안쪽으로 본 배열)"""
    b = b.astype(np.int16)
    몫 = (b > 2).mean(axis=1)
    평 = b.mean(axis=1)
    e = 0
    while e < len(몫) and 몫[e] <= 완전띠몫 and 평[e] <= 완전띠평균:
        e += 1
    if e < 완전띠줄 or e + 8 >= len(몫):
        return 0, {}
    뛰 = float(몫[e:e + 4].max())
    높이 = float(평[e + 4:e + 8].mean() - 평[:e].mean())
    값 = {"완전띠": e, "뛰기": round(뛰, 2), "계단높이": round(높이, 1)}
    if 뛰 < 계단뛰기 or 높이 < 계단높이:
        return 0, 값
    # 두께는 «그림이 다 시작한 줄»까지 — 띠 끝 몇 줄은 압축 번짐으로 반쯤 어둡다(189.4초 78~86줄)
    return e + int(np.argmax(몫[e:e + 4] >= 계단뛰기)), 값


def 한장(a):
    """한 장의 테두리. 돌려줌 dict:
      테두리 = (x0, y0, x1, y1) 진짜 띠를 뺀 그림 자리 — 테두리가 없으면 None
      변 = 변마다 잰 값(시험·로그용)
    «진짜 띠» 변 = ①순흑+②곧은 경계 이거나, ③완전 검정 띠의 줄 전체 계단. 그런 변이 하나도 없으면 테두리 없음.
    진짜 띠 변이 있는 장에서는 ①순흑 인 다른 변도 띠로 깎는다(아래 띠 속 자막처럼 경계가 글자에서 끊긴 변)."""
    if a is None:
        return {"테두리": None, "변": {}, "까닭": "프레임 없음"}
    a = 밝기(a)                                   # RGB 가 와도 같은 자(밝기)로 잰다
    H, W = a.shape
    밝 = a > 어둠
